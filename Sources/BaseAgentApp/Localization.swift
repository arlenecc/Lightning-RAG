    private static func wordByWord(_ text: String) -> String {
        var result = text
        for (zh, en) in wordTable.sorted(by: { $0.key.count > $1.key.count }) {
            result = result.replacingOccurrences(of: zh, with: en)
        }
        return result
    }

    /// 对含插值的字符串：运行时文本里的数字/标识符会被归一化后再查表。
    /// 例如源码 "第 \(n) 页" 运行时为 "第 3 页"，归一化后查 "第 {N} 页" → "Page {N}"，
    /// 再把 {N} 还原为 3。
    private static func fallbackPattern(_ text: String) -> String? {
        var placeholders: [String] = []
        var normalized = ""
        var buffer = ""
        func flushBuffer() {
            guard !buffer.isEmpty else { return }
            let token = "{\(placeholders.count)}"
            placeholders.append(buffer)
            normalized += token
            buffer = ""
        }
        for character in text {
            // 只把 ASCII 字母/数字当变量；中文 isLetter 为 true，不能归一化掉。
            let isVariable = character.isASCII && (character.isNumber || character.isLetter)
            if isVariable {
                buffer.append(character)
            } else {
                flushBuffer()
                normalized.append(character)
            }
        }
        flushBuffer()
        guard placeholders.count > 0, let english = table[normalized] else { return nil }
        var result = english
        for (index, value) in placeholders.enumerated() {
            result = result.replacingOccurrences(of: "{\(index)}", with: value)
        }
        return result
    }
}

