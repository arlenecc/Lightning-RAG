存 `memory/history_insight.md`（不存在则创建），格式自定。产物是数据库，不是报告——每条发现都是下游任务的输入，遗漏即损失。

产物包含三个持久状态（可以是多个文件或一个文件内的多个区域）：
1. **活动知识层** — 每次扫描读取、更新、写回。记录所有识别到的活动及其最终分类。
