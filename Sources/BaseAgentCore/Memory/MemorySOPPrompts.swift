### 情绪事件

标记语气上的明显波动，不是内容上的。

**标记**：愤怒/质问/责备、讽刺挖苦、惊喜感激、反复纠正后语气突变、沮丧/无奈、预期落空后的失望或方向突变。

**不标记**：纯功能指令、语气平和的反馈、讨论负面话题但本人情绪稳定。

### 持续活动与已消失事项

维护一个持久的活动知识层（存 `memory/history_insight.md`）。这是跨次运行的持久状态——每次扫描读取它、更新它、写回它。它不是报告，是数据库。

