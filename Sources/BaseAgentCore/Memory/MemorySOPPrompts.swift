# 历史重点挖掘 SOP

从用户历史对话中挖掘值得长期保留的重点：情绪事件、持续活动、已消失事项。

## 数据源

`memory/raw_session/all_history.txt`。

## 执行约束

- 增量：维护已处理 session 列表，每次只扫新 session
